pub(super) fn generate_ffi(tcx: &TypeContext, dylib_name: &str) -> String {
    let mut out = String::from(
        "// @generated by diplomat-tool's experimental Safe Rust backend.\n\
         #![allow(dead_code)]\n\
         // ZST error structs (`MyZst`) and similar Diplomat layouts are the\n\
         // provider's ABI; rustc still flags empty structs in `extern` blocks.\n\
         #![allow(improper_ctypes)]\n\n\
         // The ABI types come from `diplomat-runtime` instead of being transcribed
         // here: a hand-maintained mirror with no layout check is a silent-UB hazard.
         // Re-exported so the sibling modules can name them as `ffi::DiplomatSlice`.
         pub(super) use diplomat_runtime::{
             DiplomatOption, DiplomatOwnedSlice, DiplomatResult, DiplomatSlice, DiplomatSliceMut,
             DiplomatWrite,\n\
         };\n\n",
    );

    for opaque in tcx.opaques().iter().filter(|ty| !ty.attrs.disable) {
        let name = type_def_name(TypeDef::Opaque(opaque));
        writeln!(
            out,
            "#[repr(C)]\npub struct {name} {{ _private: [u8; 0] }}\n"
        )
        .unwrap();
    }
    for strct in tcx.structs().iter().filter(|ty| !ty.attrs.disable) {
        if !struct_needs_abi_mirror(strct, tcx) {
            continue;
        }
        let name = type_def_name(TypeDef::Struct(strct));
        let (params, _) = struct_generics(strct);
        writeln!(out, "#[repr(C)]\npub struct {name}{params} {{").unwrap();
        for field in &strct.fields {
            writeln!(
                out,
                "    pub(super) {}: {},",
                field_name(field),
                ffi_struct_field_type(&field.ty, strct, tcx)
            )
            .unwrap();
        }
        out.push_str("}\n\n");
    }
    writeln!(out, "#[link(name = {:?})]\nextern \"C\" {{", dylib_name).unwrap();
    for opaque in tcx.opaques().iter().filter(|ty| !ty.attrs.disable) {
        let name = type_def_name(TypeDef::Opaque(opaque));
        writeln!(
            out,
            "    pub(super) fn {}(this: *mut {name});",
            opaque.dtor_abi_name
        )
        .unwrap();
        emit_extern_methods(&mut out, &opaque.methods, tcx);
    }
    // An inherent method on a value type crosses the same ABI as an opaque's; the
    // receiver is the value or a pointer to it rather than a handle.
    for strct in tcx.structs().iter().filter(|ty| !ty.attrs.disable) {
        emit_extern_methods(&mut out, &strct.methods, tcx);
    }
    for enm in tcx.enums().iter().filter(|ty| !ty.attrs.disable) {
        emit_extern_methods(&mut out, &enm.methods, tcx);
    }
    out.push_str("}\n");
    out
}

fn emit_extern_methods(out: &mut String, methods: &[hir::Method], tcx: &TypeContext) {
    for method in methods.iter().filter(|method| !method.attrs.disable) {
        let ret_generics = ffi_return_generics(&method.output, tcx);
        write!(out, "    pub(super) fn {}{ret_generics}(", method.abi_name).unwrap();
        let mut params = Vec::new();
        if let Some(param_self) = &method.param_self {
            params.push(format!("this: {}", ffi_self_type(&param_self.ty, tcx)));
        }
        params.extend(
            method
                .params
                .iter()
                .map(|param| format!("{}: {}", param.name, ffi_input_type(&param.ty, tcx))),
        );
        if method.output.is_write() {
            params.push("write: *mut DiplomatWrite".into());
        }
        write!(out, "{}", params.join(", ")).unwrap();
        let ret = ffi_return_type(&method.output, tcx);
        if ret == "()" {
            writeln!(out, ");").unwrap();
        } else {
            writeln!(out, ") -> {ret};").unwrap();
        }
    }
}

pub(super) fn generate_lib() -> String {
    String::from(
        "//! Safe Rust bindings generated over a Diplomat native ABI.\n\
         //!\n\
         //! The unsafe ABI layer lives in the private `ffi` module; the public API is\n\
         //! re-exported from this crate root.\n\n\
         #![allow(clippy::needless_lifetimes)]\n\
         #![allow(clippy::new_without_default)]\n\
         // The generated surface is the provider's declarations rendered in Rust, so\n\
         // a provider that declares `Result<T, ()>`, an inherent `new`/`from_str`,\n\
         // or a `len` without an `is_empty` gets exactly that. Re-shaping those\n\
         // would change the API this backend offers for no ABI reason; names are\n\
         // different and *are* restyled (see `method_name`).\n\
         #![allow(clippy::result_unit_err)]\n\
         #![allow(clippy::should_implement_trait)]\n\
         #![allow(clippy::inherent_to_string)]\n\
         #![allow(clippy::disallowed_names)]\n\
         #![allow(clippy::len_without_is_empty)]\n\n\
         mod ffi;\n\
         mod opaques;\n\
         mod private;\n\
         mod types;\n\n\
         pub use opaques::*;\n\
         pub use types::*;\n",
    )
}

/// Sealed capability traits plus the unsafe ABI reconstruction helpers.
pub(super) fn generate_private(tcx: &TypeContext) -> String {
    let mut out = String::from(
        "//! Sealed capability traits and unsafe ABI reconstruction helpers.\n\
         //!\n\
         //! This module is private, so downstream crates cannot name the sealed traits and\n\
         //! therefore cannot implement the public capability traits themselves. The helpers\n\
         //! may be unused for a given provider, hence the `dead_code` allow.\n\
         #![allow(dead_code)]\n\n\
         /// Rebuild a `char` from the `DiplomatChar` a provider returned.\n\
         ///\n\
         /// The ABI carries a `u32` code point; a `char` is only the code points that\n\
         /// are Unicode scalar values. A provider written in Rust cannot produce an\n\
         /// invalid one — its field is a `char` — so this is unreachable in contract\n\
         /// and is a hard error rather than a lossy fallback.\n\
         pub(crate) fn char_from_u32(value: u32) -> char {\n\
             char::from_u32(value)\n\
                 .expect(\"provider returned a DiplomatChar outside the Unicode scalar range\")\n\
         }\n\n",
    );
    for opaque in tcx.opaques().iter().filter(|ty| !ty.attrs.disable) {
        let name = type_def_name(TypeDef::Opaque(opaque));
        writeln!(out, "pub trait {name}SharedSealed {{").unwrap();
        writeln!(
            out,
            "    fn __as_const_ptr(&self) -> *const crate::ffi::{name};"
        )
        .unwrap();
        out.push_str("}\n");
        writeln!(out, "pub trait {name}MutSealed: {name}SharedSealed {{").unwrap();
        writeln!(
            out,
            "    fn __as_mut_ptr(&mut self) -> *mut crate::ffi::{name};"
        )
        .unwrap();
        out.push_str("}\n");
    }
    out.push('\n');
    out.push_str(
        r#"    /// Reconstruct a validated `&str` from a provider-returned UTF-8 slice.
    ///
    /// The runtime can turn a `DiplomatSlice` back into a `&[T]`, but
    /// `DiplomatUtf8StrSlice`'s field is private, so this is the one conversion the
    /// runtime cannot express and the generated crate keeps locally.
    ///
    /// # Safety
    ///
    /// The caller must uphold the provider's validity, alignment, aliasing, UTF-8,
    /// and lifetime contract for the slice for the returned lifetime. The ABI type
    /// cannot express UTF-8 validity, so the provider must send valid UTF-8.
    pub(crate) unsafe fn utf8_str_from_slice<'a>(
        slice: diplomat_runtime::DiplomatSlice<'a, u8>,
    ) -> &'a str {
        core::str::from_utf8_unchecked(<&[u8]>::from(slice))
    }

    /// Drive a `DiplomatWrite` out-parameter and return the written UTF-8.
    ///
    /// The writer is constructed here, handed to the provider as a raw pointer, and
    /// never exposed on the public API. The copy out of `as_bytes` is what keeps the
    /// generated crate compatible with published `diplomat-runtime` 0.16, which has
    /// `RustWriteVec` but not a consuming `into_string`.
    pub(crate) fn with_write<R>(
        f: impl FnOnce(*mut diplomat_runtime::DiplomatWrite) -> R,
    ) -> (R, String) {
        let mut write = diplomat_runtime::rust_interop::RustWriteVec::with_capacity(0);
        // SAFETY: this is the only DiplomatWrite in scope; it was created by
        // diplomat_buffer_write_create and is not swapped with another instance.
        let result = f(unsafe { write.borrow_mut() });
        let text = String::from_utf8(write.borrow().as_bytes().to_vec())
            .expect("DiplomatWrite contains non-UTF-8 bytes");
        (result, text)
    }

"#,
    );
    out
}

/// One module per opaque type, re-exported flat from the `opaques` module.
pub(super) fn generate_opaques_index(tcx: &TypeContext) -> String {
    let mut out = String::from("//! Generated opaque wrappers, one module per type.\n\n");
    let opaques: Vec<_> = tcx
        .opaques()
        .iter()
        .filter(|ty| !ty.attrs.disable)
        .collect();
    for opaque in &opaques {
        writeln!(out, "mod {};", opaque_module_name(opaque)).unwrap();
    }
    if !opaques.is_empty() {
        out.push('\n');
    }
    for opaque in &opaques {
        writeln!(out, "pub use {}::*;", opaque_module_name(opaque)).unwrap();
    }
    out
}

/// The contents of a single `src/opaques/<module>.rs` file.
pub(super) fn generate_opaque_file(
    tcx: &TypeContext,
    opaque: &hir::OpaqueDef,
    docs_url_gen: &DocsUrlGenerator,
) -> String {
    let mut out = String::from(
        "use core::fmt;\n\
         use core::marker::PhantomData;\n\
         use core::ptr::NonNull;\n\
         use std::rc::Rc;\n\n\
         use crate::ffi;\n",
    );
    if opaque_uses_value_types(opaque) {
        out.push_str("use crate::types::*;\n");
    }
    out.push('\n');
    emit_opaque(&mut out, opaque, tcx, docs_url_gen);
    out
}
